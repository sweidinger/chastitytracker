export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const locale = await getLocale();
  const messages = await getMessages();
  const session = await auth();
  const sessionUserId = (session?.user as { id?: string } | undefined)?.id ?? null;

  // Cross-device adoption: if this browser has no locale cookie yet but the account has a stored
  // language, adopt it once. Guarded on cookie-absence (not mismatch) so it never fights a choice
  // the user just made on this device while the JWT still carries the previous value.
  const hasLocaleCookie = (await cookies()).has("locale");
  const sessionLocale = (session?.user as { locale?: string } | undefined)?.locale;
  const localeToAdopt = !hasLocaleCookie && isValidLocale(sessionLocale) ? sessionLocale : null;

  return (
    <html lang={locale} suppressHydrationWarning>
      <head>
        {/* Prevent iOS WebKit from auto-linking phone numbers / dates / addresses
            — those DOM mutations happen before React hydration and cause #418 */}
        <meta name="format-detection" content="telephone=no, date=no, address=no, email=no" />
        {/* iOS splash screens — portrait only */}
        {splashScreens.map(({ w, h, r, src }) => (
          <link
            key={src}
            rel="apple-touch-startup-image"
            href={src}
            media={`(device-width: ${w}px) and (device-height: ${h}px) and (-webkit-device-pixel-ratio: ${r}) and (orientation: portrait)`}
          />
        ))}
      </head>
      <body className={`${geistSans.variable} ${jetbrainsMono.variable} antialiased`} suppressHydrationWarning>
        {IS_BETA && (
          <>
            <div aria-hidden="true" style={{ position: "fixed", inset: 0, border: "4px solid #ef4444", pointerEvents: "none", zIndex: 2147483647 }} />
            <div aria-hidden="true" style={{ position: "fixed", top: "calc(env(safe-area-inset-top, 0px) + 4px)", left: "50%", transform: "translateX(-50%)", background: "#ef4444", color: "#fff", fontSize: "11px", fontWeight: 700, letterSpacing: "1.5px", padding: "2px 12px", borderRadius: "0 0 8px 8px", pointerEvents: "none", zIndex: 2147483647 }}>BETA</div>
          </>
        )}
        <NextIntlClientProvider messages={messages}>
          <ToastProvider>
            {localeToAdopt && <LocaleCookieSync locale={localeToAdopt} />}
            {children}
            <AppLockLoader />
            <Heartbeat buildDate={process.env.BUILD_DATE ?? "local"} initialUserId={sessionUserId ?? null} />
            <NativePushRouter />
            <AirlockDeepLinkRouter />
            <Script id="sw-register" strategy="afterInteractive">{`
              if ('serviceWorker' in navigator && window.location.hostname !== 'localhost') {
                navigator.serviceWorker.register('/sw.js').catch(function(err) {
                  console.warn('[SW] registration failed:', err);
                });
              }
              /* Das Badge wird NICHT mehr blind geräumt: es zählt seit v4.56.0 ungelesene
                 Nachrichten, und ein unbedingtes clearAppBadge() beim Start/Resume hätte es nach
                 dem ersten Blick in die App für immer gelöscht. Gesetzt wird es jetzt am Zustand,
                 in AppBadgeSync (Header). */
            `}</Script>
          </ToastProvider>
        </NextIntlClientProvider>
      </body>
    </html>
  );
}
