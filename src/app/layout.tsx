// Beta-Instanz kennzeichnet sich per INSTANCE_LABEL (nur in der Beta-.env gesetzt) — eigener
// Name, eigenes App-Icon und rotes Theme, damit sich die iPhone-Home-App und die Optik klar
// von Prod abheben. Prod setzt die Variable nicht → unveraendert.
const IS_BETA = process.env.INSTANCE_LABEL === "BETA";

export async function generateMetadata(): Promise<Metadata> {
  const title = IS_BETA ? "KG Tracker BETA" : "KG Tracker";
  return {
    title,
    description: "Keuschheitsgürtel Tracking",
    manifest: "/manifest.webmanifest",
    appleWebApp: {
      capable: true,
      statusBarStyle: "black-translucent",
      title,
    },
    icons: {
      icon: IS_BETA ? "/icon-beta.svg" : "/icon.svg",
      apple: IS_BETA ? "/icon-192-beta.png" : "/icon-192.png",
    },
  };
}

export function generateViewport(): Viewport {
  return {
    width: "device-width",
    initialScale: 1,
    viewportFit: "cover",
    themeColor: IS_BETA ? "#ef4444" : "#111827",
  };
}

